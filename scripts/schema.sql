-- ---------- 1. 认证 ----------
CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(64)  NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    display_name  varchar(64)  NOT NULL,
    gender        varchar(8)   NULL,              -- 男 / 女（注册时填写，可空）
    age           integer      NULL,              -- 年龄（可空）
    status        varchar(8)   NOT NULL DEFAULT '启用' CHECK (status IN ('启用', '停用')), -- 启用状态
    created_at    timestamp    NOT NULL DEFAULT now(),
    updated_at    timestamp    NOT NULL DEFAULT now()
);

-- ---------- 2. 身材数据（4 张拆分表，均按 (user_id, record_date) 唯一） ----------
-- 表1：身高 / 体重 / 体脂率
CREATE TABLE body_basic_records (
    id           integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer      NOT NULL,
    record_date  date         NOT NULL,
    height_cm    numeric(6,2) NULL,   -- 身高
    weight_kg    numeric(10,2) NULL,   -- 体重（任意数值、保留两位小数）
    body_fat_pct numeric(6,2) NULL,   -- 体脂率 %
    created_at   timestamp    NOT NULL DEFAULT now(),
    updated_at   timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_body_basic_user_date UNIQUE (user_id, record_date)
);
CREATE INDEX ix_body_basic_records_user_id ON body_basic_records (user_id);

-- 表2：期望体重 / 期望体脂率
CREATE TABLE body_basic_goal (
    id                 integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            integer      NOT NULL,
    record_date        date         NOT NULL,
    target_weight_kg   numeric(10,2) NULL,   -- 目标体重（任意数值、保留两位小数）
    target_body_fat_pct numeric(6,2) NULL,  -- 目标体脂率 %
    created_at         timestamp    NOT NULL DEFAULT now(),
    updated_at         timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_body_basic_goal_user_date UNIQUE (user_id, record_date)
);
CREATE INDEX ix_body_basic_goal_user_id ON body_basic_goal (user_id);

-- 表3：颈围 / 肩宽 / 臂围 / 胸围 / 腰围 / 臀围 / 大腿围 / 小腿围
CREATE TABLE body_dimensions_records (
    id                integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer      NOT NULL,
    record_date       date         NOT NULL,
    neck_cm           numeric(6,2) NULL,   -- 颈围
    shoulder_width_cm numeric(6,2) NULL,   -- 肩宽
    arm_circ_cm       numeric(6,2) NULL,   -- 臂围
    chest_circ_cm     numeric(6,2) NULL,   -- 胸围
    waist_circ_cm     numeric(6,2) NULL,   -- 腰围
    hip_circ_cm       numeric(6,2) NULL,   -- 臀围
    thigh_circ_cm     numeric(6,2) NULL,   -- 大腿围
    calf_circ_cm      numeric(6,2) NULL,   -- 小腿围
    created_at        timestamp    NOT NULL DEFAULT now(),
    updated_at        timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_body_dimensions_records_user_date UNIQUE (user_id, record_date)
);
CREATE INDEX ix_body_dimensions_records_user_id ON body_dimensions_records (user_id);

-- 表4：目标臂围 / 目标胸围 / 目标腰围 / 目标臀围 / 目标大腿围 / 目标小腿围
CREATE TABLE body_dimensions_goal (
    id                  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             integer      NOT NULL,
    record_date         date         NOT NULL,
    target_arm_circ_cm  numeric(6,2) NULL,   -- 目标臂围
    target_chest_circ_cm numeric(6,2) NULL,  -- 目标胸围
    target_waist_circ_cm numeric(6,2) NULL,  -- 目标腰围
    target_hip_circ_cm  numeric(6,2) NULL,   -- 目标臀围
    target_thigh_circ_cm numeric(6,2) NULL,  -- 目标大腿围
    target_calf_circ_cm numeric(6,2) NULL,   -- 目标小腿围
    created_at          timestamp    NOT NULL DEFAULT now(),
    updated_at          timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_body_dimensions_goal_user_date UNIQUE (user_id, record_date)
);
CREATE INDEX ix_body_dimensions_goal_user_id ON body_dimensions_goal (user_id);

-- ---------- 3. 健身训练（一日可多个计划，按 id 区分） ----------
CREATE TABLE training_records (
    id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    date       date         NOT NULL,
    status     varchar(16)  NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'recorded')),
    remark     varchar(255) NULL,                  -- 备注（计划/记录均可填）
    start_time  timestamp    NULL,                  -- 开始训练时刻（仅记录态填写；2026-11-04 由 started_at 改名）
    end_time    timestamp    NULL,                  -- 结束训练时刻（仅记录态填写；2026-11-04 由 saved_at 改名）
    duration_s integer      NULL,                  -- 训练时长（秒，仅记录态；填了起止时间自动推导，也可手填）
    avg_heart_rate integer NULL,
    max_heart_rate integer NULL,
    calories numeric(8,2) NULL,
    created_at timestamp    NOT NULL DEFAULT now(),
    updated_at timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX ix_training_records_user_id ON training_records (user_id);
CREATE INDEX ix_training_records_user_date ON training_records (user_id, date);
CREATE INDEX ix_training_records_user_date_id ON training_records (user_id, date, id);

CREATE TABLE training_records_items (
    id               integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_id          integer       NOT NULL REFERENCES training_records (id) ON DELETE CASCADE,
    sort             integer       NOT NULL DEFAULT 0,
    exercise_name    varchar(128)  NOT NULL,
    body_part        varchar(32)   NULL,            -- 部位（可空）
    weight_kg        numeric(10,2) NULL,            -- 重量 kg（可空，任意数值、保留两位小数）
    sets             integer       NULL,            -- 组数（可空）
    reps             varchar(32)   NULL,            -- 每组个数（字符串，如 '10+8+6'，可空）
    target_weight_kg numeric(10,2) NULL,            -- 期望突破重量（计划/记录均可填，任意数值、保留两位小数）
);
CREATE INDEX ix_training_records_items_training_id ON training_records_items (training_id);

CREATE TABLE training_notes (
    id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_id       integer      NOT NULL UNIQUE REFERENCES training_records (id) ON DELETE CASCADE,
    rating        smallint     NULL,                      -- 自我评估 1~5 星
    best_movement varchar(128) NULL,                      -- 最佳动作（2026-11 新增）
    notes    text         NULL,                      -- 复盘/反思（2026-11 新增）
    next_steps    text         NULL,                      -- 下一步想法（2026-11 新增）
    status_text   text         NULL                       -- 旧版心得文本（仅历史数据）
);

-- ---------- 4. 游泳（计划态需距离；记录态需距离/时长；remark 均可填） ----------
CREATE TABLE swim_records (
    id             integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        integer       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    date           date          NOT NULL,
    status         varchar(16)   NOT NULL DEFAULT 'recorded' CHECK (status IN ('planned', 'recorded')),
    start_time     timestamp     NULL,
    end_time       timestamp     NULL,
    remark         varchar(255)  NULL,                          -- 备注（计划/记录均可填）
    distance_m     integer       NULL,                          -- 距离（计划/记录态必填）
    duration_s     integer       NULL,                          -- 存秒（记录态必填，计划态可空）
    avg_heart_rate integer       NULL,
    max_heart_rate integer       NULL,
    total_strokes  integer       NULL,
    main_stroke    varchar(16)   NULL,               -- 主泳姿（两态均可空，填写时校验合法值）
    laps           integer       NULL,
    calories       numeric(8,2)  NULL,
    avg_stroke_rate double precision NULL,          -- 平均划频（2026-11 新增；未填时由 total_strokes/duration 派生）
    created_at     timestamp     NOT NULL DEFAULT now(),
    updated_at     timestamp     NOT NULL DEFAULT now()
);
CREATE INDEX ix_swim_records_user_id ON swim_records (user_id);
CREATE INDEX ix_swim_records_user_date ON swim_records (user_id, date);
CREATE INDEX ix_swim_records_user_date_id ON swim_records (user_id, date, id);

CREATE TABLE swim_notes (
    id             integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    swim_id        integer  NOT NULL UNIQUE REFERENCES swim_records (id) ON DELETE CASCADE,
    rating         smallint NULL,                          -- 自我评估 1~5 星
    stroke_insight text NULL,                          -- 泳姿是否有感悟/进步
    notes          text     NULL                           -- 其他
);

-- ---------- 5. 舞蹈（计划和记录态均需舞种/星级，时长可空；remark 均可填） ----------
CREATE TABLE dance_records (
    id             integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        integer       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    date           date          NOT NULL,
    start_time     timestamp     NULL,                          -- 课程开始时间（含日期与时分，2026-11 新增）
    end_time       timestamp     NULL,                          -- 课程结束时间（2026-11 新增）
    status         varchar(16)   NOT NULL DEFAULT 'recorded' CHECK (status IN ('planned', 'recorded')),
    remark         varchar(255)  NULL,                          -- 备注（计划/记录均可填）
    dance_type     varchar(32)   NULL,                          -- 舞种（计划/记录态必填）
    stars          smallint      NULL,                          -- 1~5（计划/记录态必填）
    teacher        varchar(64)   NULL,                          -- 舞蹈老师
    style          varchar(64)   NULL,
    duration_s     integer       NULL,                          -- 存秒（两态可空；可由起止时间推导）
    avg_heart_rate integer       NULL,
    max_heart_rate integer       NULL,
    calories       numeric(8,2)  NULL,
    created_at     timestamp     NOT NULL DEFAULT now(),
    updated_at     timestamp     NOT NULL DEFAULT now()
);
CREATE INDEX ix_dance_records_user_id ON dance_records (user_id);
CREATE INDEX ix_dance_records_user_date ON dance_records (user_id, date);
CREATE INDEX ix_dance_records_user_date_id ON dance_records (user_id, date, id);

CREATE TABLE dance_notes (
    id           integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dance_id     integer  NOT NULL UNIQUE REFERENCES dance_records (id) ON DELETE CASCADE,
    rating       smallint NULL,                          -- 自我评估 1~5 星
    video_effect smallint NULL,                          -- 视频效果 1~5 星
    notes      text     NULL                           -- 感悟
);

-- ---------- 6. 生理周期 ----------
-- 四档状态按周期段内日序及疼痛实时推算；日历浅蓝绿/绿/黄/粉配色与窄屏状态短名仅在前端维护，不作为数据库字段。
-- cycle_settings 语义为「参考值」：不随记录变化，只用于当前段、预测段、补推段与未填结束日的记录。
CREATE TABLE cycle_settings (
    user_id       integer   NOT NULL PRIMARY KEY REFERENCES users (id),
    cycle_length  integer   NOT NULL DEFAULT 28,
    period_length integer   NOT NULL DEFAULT 5,
    updated_at    timestamp NOT NULL DEFAULT now()
);

CREATE TABLE period_records (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer NOT NULL,
    start_date date    NOT NULL,                     -- 月经开始日（分段依据）；应用层校验同用户不重复、相邻首日间隔下限
    end_date   date    NULL,                         -- 结束日（可后补；经期长度 = 结束 - 开始 + 1，不落库）
    created_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX ix_period_records_user_id ON period_records (user_id);

CREATE TABLE daily_pain_logs (
    id         integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer  NOT NULL,
    log_date   date     NOT NULL,
    pain_level smallint NOT NULL DEFAULT 0,          -- 0无/1轻/2中/3重
    created_at timestamp NOT NULL DEFAULT now(),
    CONSTRAINT uq_pain_user_date UNIQUE (user_id, log_date)
);
CREATE INDEX ix_daily_pain_logs_user_id ON daily_pain_logs (user_id);

-- ---------- 状态记录：食欲 / 肌肉疼痛 / 炎症（按天，每类每天一行；非运动模块，无计划态/时长/心率/热量） ----------
CREATE TABLE appetite_record (
    id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    date       date         NOT NULL,
    star       smallint     NULL,
    remark     varchar(255) NULL,
    created_at timestamp    NOT NULL DEFAULT now(),
    updated_at timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_appetite_user_date UNIQUE (user_id, date)
);
CREATE INDEX ix_appetite_record_user_id ON appetite_record (user_id);
CREATE INDEX ix_appetite_record_user_date_id ON appetite_record (user_id, date, id);

CREATE TABLE myalgia_record (
    id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    date       date         NOT NULL,
    star       smallint     NULL,
    remark     varchar(255) NULL,
    created_at timestamp    NOT NULL DEFAULT now(),
    updated_at timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_myalgia_user_date UNIQUE (user_id, date)
);
CREATE INDEX ix_myalgia_record_user_id ON myalgia_record (user_id);
CREATE INDEX ix_myalgia_record_user_date_id ON myalgia_record (user_id, date, id);

CREATE TABLE inflammation_record (
    id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    date       date         NOT NULL,
    star       smallint     NULL,
    remark     varchar(255) NULL,
    created_at timestamp    NOT NULL DEFAULT now(),
    updated_at timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_inflammation_user_date UNIQUE (user_id, date)
);
CREATE INDEX ix_inflammation_record_user_id ON inflammation_record (user_id);
CREATE INDEX ix_inflammation_record_user_date_id ON inflammation_record (user_id, date, id);

-- ---------- 7. AI Agent（会话元数据；消息由 checkpointer 框架表管理） ----------
CREATE TABLE agent_conversations (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title           varchar(64)  NOT NULL DEFAULT '新会话',
    model_name      varchar(64)  NULL,                  -- 会话级模型（可空，用默认模型）
    thread_id       uuid         NOT NULL UNIQUE,        -- LangGraph 线程 ID（checkpointer 键）
    last_message_at timestamp    NULL,                  -- 最近消息时间（列表排序冗余）
    created_at      timestamp    NOT NULL DEFAULT now(),
    updated_at      timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX ix_agent_conversations_user_last ON agent_conversations (user_id, last_message_at DESC);

-- checkpointer 框架表（checkpoints / checkpoint_blobs / checkpoint_writes / checkpoint_migrations）
-- 由应用启动时 PostgresSaver.setup() 在 langgraph schema 内自动建表（版本化迁移），此处只建 schema。
CREATE SCHEMA IF NOT EXISTS langgraph;

