"""健康档案行式化迁移（幂等）：把旧 1:1 JSON 档案迁移成一行一条记录。

旧结构：health_profile(user_id PK, answers jsonb, custom_questions jsonb, completed_at, ...)
新结构：id PK + user_id 非唯一外键 + aspect/item_key/answer/source/set_id 等。

用法：
    python scripts/migrate_health_profile_entries.py

说明：
- 旧固定题按 questions.py 的 aspect 映射迁移；
- 旧定制问题按 custom_questions.sets 迁移，未回答的题保留 answer=NULL；
- completed_at 不再存库，按“有效答案数 ≥ 3”从行派生；
- 整个迁移在一个事务内完成，失败不会留下半迁移数据。
"""
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import text

from app.modules.profile.aspects import ASPECT_KEYS, aspect_for_question
from app.modules.profile.probe import MAX_SETS, PROBE_PREFIX, PROBE_PERSONA_KEY
from app.modules.profile.questions import QUESTIONS
from database import engine

TABLE_SQL = """
CREATE TABLE health_profile (
    id                integer   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    aspect            varchar(32) NOT NULL,
    item_key          varchar(64) NOT NULL,
    label             varchar(120) NOT NULL DEFAULT '',
    hint              varchar(120) NOT NULL DEFAULT '',
    placeholder       varchar(120) NOT NULL DEFAULT '',
    max_length        integer   NOT NULL DEFAULT 200,
    answer            text      NULL,
    source            varchar(16) NOT NULL DEFAULT 'fixed',
    set_id            varchar(16) NULL,
    persona_key       varchar(48) NULL,
    set_generated_at  timestamp NULL,
    sort_order        integer   NOT NULL DEFAULT 0,
    created_at        timestamp NOT NULL DEFAULT now(),
    updated_at        timestamp NOT NULL DEFAULT now(),
    CONSTRAINT uq_health_profile_user_item UNIQUE (user_id, item_key),
    CONSTRAINT ck_health_profile_aspect CHECK (
        aspect IN (
            'goal', 'diet', 'exercise', 'training', 'sleep', 'lifestyle',
            'medical', 'cycle', 'psych', 'environment', 'preference', 'other'
        )
    ),
    CONSTRAINT ck_health_profile_source CHECK (source IN ('fixed', 'probe', 'user'))
)
"""

INDEXES = [
    "CREATE INDEX idx_health_profile_user_aspect ON health_profile (user_id, aspect)",
]

COMMENTS = [
    "COMMENT ON TABLE health_profile IS '健康/运动档案（一用户多行，按 aspect 记录开放式答案）'",
    "COMMENT ON COLUMN health_profile.id IS '档案记录主键'",
    "COMMENT ON COLUMN health_profile.user_id IS '用户主键 + FK，删除账号时级联删除；非唯一，一用户多行'",
    "COMMENT ON COLUMN health_profile.aspect IS '档案方面，固定模板见 app/modules/profile/aspects.py'",
    "COMMENT ON COLUMN health_profile.item_key IS '用户内稳定题目 key：固定题见 questions.py，定制题为 probe_<set_id>_<qN>'",
    "COMMENT ON COLUMN health_profile.label IS '题目标题'",
    "COMMENT ON COLUMN health_profile.hint IS '填写提示'",
    "COMMENT ON COLUMN health_profile.placeholder IS '占位文案'",
    "COMMENT ON COLUMN health_profile.max_length IS '答案最大字数'",
    "COMMENT ON COLUMN health_profile.answer IS '用户文本答案；为空表示题目已生成但未回答'",
    "COMMENT ON COLUMN health_profile.source IS '来源：fixed 固定问卷 / probe 角色定制 / user 用户自建'",
    "COMMENT ON COLUMN health_profile.set_id IS '定制问题所属套 id；固定题为空'",
    "COMMENT ON COLUMN health_profile.persona_key IS '生成定制问题的角色 key'",
    "COMMENT ON COLUMN health_profile.set_generated_at IS '定制问题套生成时间'",
    "COMMENT ON COLUMN health_profile.sort_order IS '同套/同方面的展示顺序'",
    "COMMENT ON COLUMN health_profile.created_at IS '创建时间'",
    "COMMENT ON COLUMN health_profile.updated_at IS '更新时间（ORM onupdate 自动刷新）'",
]

INSERT_SQL = """
INSERT INTO health_profile (
    user_id, aspect, item_key, label, hint, placeholder, max_length, answer,
    source, set_id, persona_key, set_generated_at, sort_order, created_at, updated_at
) VALUES (
    :user_id, :aspect, :item_key, :label, :hint, :placeholder, :max_length, :answer,
    :source, :set_id, :persona_key, :set_generated_at, :sort_order, :created_at, :updated_at
)
"""

# 旧定制问题 group 到新 aspect 的兼容映射。
LEGACY_GROUP_ASPECTS = {
    "目标与动机": "goal",
    "目标与节奏": "goal",
    "饮食营养": "diet",
    "训练安排": "training",
    "训练方式与条件": "training",
    "睡眠恢复": "sleep",
    "疼痛炎症": "medical",
    "生理周期": "cycle",
    "压力情绪": "psych",
    "时间场地": "environment",
    "疾病用药": "medical",
    "体重体成分": "goal",
    "其他": "other",
    "本次定制": "other",
}


def _aspect(raw: dict) -> str:
    aspect = str(raw.get("aspect") or "").strip().lower()
    if aspect in ASPECT_KEYS:
        return aspect
    return LEGACY_GROUP_ASPECTS.get(str(raw.get("group") or ""), "other")


def _dt(value):
    if isinstance(value, datetime):
        return value
    if isinstance(value, str):
        try:
            return datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError:
            return None
    return None


def _insert(conn, row: dict) -> None:
    conn.execute(text(INSERT_SQL), row)


def _create_new_table(conn) -> None:
    conn.execute(text(TABLE_SQL))
    for sql in INDEXES:
        conn.execute(text(sql))
    for sql in COMMENTS:
        conn.execute(text(sql))


def _migrate_legacy(conn, has_custom_questions: bool = True) -> int:
    """把旧表改名后逐行迁移；返回迁移记录数。"""
    conn.execute(text("ALTER TABLE health_profile RENAME TO health_profile_legacy"))
    _create_new_table(conn)

    select_columns = "user_id, answers, created_at, updated_at"
    if has_custom_questions:
        select_columns = "user_id, answers, custom_questions, created_at, updated_at"
    legacy_rows = conn.execute(text(
        f"SELECT {select_columns} FROM health_profile_legacy ORDER BY user_id"
    )).mappings().all()

    count = 0
    for legacy in legacy_rows:
        user_id = legacy["user_id"]
        answers = legacy["answers"] if isinstance(legacy["answers"], dict) else {}
        custom = (
            legacy["custom_questions"]
            if has_custom_questions and isinstance(legacy["custom_questions"], dict)
            else {}
        )
        migrated_keys: set[str] = set()
        created_at = legacy["created_at"] or datetime.now()
        updated_at = legacy["updated_at"] or created_at

        for order, question in enumerate(QUESTIONS):
            value = answers.get(question["key"])
            if not isinstance(value, str) or not value.strip():
                continue
            _insert(conn, {
                "user_id": user_id,
                "aspect": aspect_for_question(question["key"]),
                "item_key": question["key"],
                "label": question["label"],
                "hint": question["hint"],
                "placeholder": question["placeholder"],
                "max_length": question["max_length"],
                "answer": value.strip(),
                "source": "fixed",
                "set_id": None,
                "persona_key": None,
                "set_generated_at": None,
                "sort_order": order,
                "created_at": created_at,
                "updated_at": updated_at,
            })
            count += 1
            migrated_keys.add(question["key"])

        sets = custom.get("sets") if isinstance(custom, dict) else None
        if not isinstance(sets, list):
            sets = []
        for item in sets[-MAX_SETS:]:
            if not isinstance(item, dict) or not item.get("set_id"):
                continue
            set_id = str(item["set_id"])
            persona_key = str(item.get("persona_key") or PROBE_PERSONA_KEY)
            generated_at = _dt(item.get("generated_at")) or created_at
            questions = item.get("questions") if isinstance(item.get("questions"), list) else []
            for order, raw_question in enumerate(questions):
                if not isinstance(raw_question, dict):
                    continue
                local_key = str(raw_question.get("local_key") or raw_question.get("key") or "")
                if not local_key:
                    continue
                item_key = str(
                    raw_question.get("key")
                    or f"{PROBE_PREFIX}{set_id}_{local_key}"
                )
                answer = answers.get(item_key)
                if isinstance(answer, str):
                    answer = answer.strip() or None
                else:
                    answer = None
                _insert(conn, {
                    "user_id": user_id,
                    "aspect": _aspect(raw_question),
                    "item_key": item_key,
                    "label": str(raw_question.get("label") or local_key)[:120],
                    "hint": str(raw_question.get("hint") or "")[:120],
                    "placeholder": str(raw_question.get("placeholder") or "")[:120],
                    "max_length": int(raw_question.get("max_length") or 200),
                    "answer": answer,
                    "source": "probe",
                    "set_id": set_id,
                    "persona_key": persona_key,
                    "set_generated_at": generated_at,
                    "sort_order": order,
                    "created_at": created_at,
                    "updated_at": updated_at,
                })
                count += 1
                migrated_keys.add(item_key)

        # 兜底：旧 answers 中仍有未归属到固定题/定制套的 key（例如旧版本遗留）
        # 也保留为行，避免迁移静默丢数据。
        for key, value in answers.items():
            if key in migrated_keys or not isinstance(value, str) or not value.strip():
                continue
            is_probe = str(key).startswith(PROBE_PREFIX)
            set_id = None
            if is_probe:
                set_id = str(key)[len(PROBE_PREFIX):].rsplit("_", 1)[0] or None
            _insert(conn, {
                "user_id": user_id,
                "aspect": "other",
                "item_key": str(key)[:64],
                "label": str(key)[:120],
                "hint": "",
                "placeholder": "",
                "max_length": 255,
                "answer": value.strip(),
                "source": "probe" if is_probe else "user",
                "set_id": set_id,
                "persona_key": PROBE_PERSONA_KEY if is_probe else None,
                "set_generated_at": created_at if is_probe else None,
                "sort_order": 999,
                "created_at": created_at,
                "updated_at": updated_at,
            })
            count += 1
            migrated_keys.add(str(key))

    conn.execute(text("DROP TABLE health_profile_legacy"))
    return count


def main() -> None:
    with engine.begin() as conn:
        columns = {
            row[0]
            for row in conn.execute(text(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = 'health_profile'"
            )).all()
        }
        if not columns:
            _create_new_table(conn)
            print("health_profile 表已按行式结构创建")
            return
        if "id" in columns and "aspect" in columns:
            for sql in COMMENTS:
                conn.execute(text(sql))
            print("health_profile 已是行式结构，无需迁移")
            return
        if "answers" not in columns:
            raise RuntimeError(f"health_profile 结构无法识别，列：{sorted(columns)}")
        moved = _migrate_legacy(conn, has_custom_questions="custom_questions" in columns)
        print(f"health_profile 行式化迁移完成，共迁移 {moved} 条记录")


if __name__ == "__main__":
    main()
