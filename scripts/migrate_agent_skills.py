SCOPE_KIND_SQL = """
ALTER TABLE agent_skills ADD CONSTRAINT ck_agent_skills_scope_kind
    CHECK (
        (scope = 'system' AND kind IN ('code', 'declarative'))
        OR (scope = 'user' AND kind = 'prompt')
    )
"""

