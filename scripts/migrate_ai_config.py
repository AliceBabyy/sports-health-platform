"""AI 模型配置三表迁移（幂等）：ai_providers / ai_models / ai_feature_routes 与中文 COMMENT。

用法：
    python scripts/migrate_ai_config.py

说明：只新增三张表，不改动已有表、不迁移数据；可重复执行。种子数据见
`scripts/seed_ai_config.py`；运行时由 `app/ai/models/registry.py` 解析，管理页为 `/system/ai`。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import text

from database import engine

DDL = [
    # 来源：一个 base_url + 一套凭据；可配多条，供不同功能点分别选用
    """
    CREATE TABLE IF NOT EXISTS ai_providers (
        id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        provider_key    varchar(48)  NOT NULL,
        name            varchar(64)  NOT NULL,
        base_url        varchar(255) NOT NULL,
        api_key_env     varchar(64)  NOT NULL DEFAULT 'AI_API_KEY',
        api_key_cipher  text         NULL,
        timeout_seconds numeric(6,1) NOT NULL DEFAULT 30.0,
        max_retries     integer      NOT NULL DEFAULT 1,
        extra_headers   jsonb        NOT NULL DEFAULT '{}'::jsonb,
        status          varchar(16)  NOT NULL DEFAULT 'active',
        remark          varchar(200) NOT NULL DEFAULT '',
        updated_by      integer      NULL,
        created_at      timestamp    NOT NULL DEFAULT now(),
        updated_at      timestamp    NOT NULL DEFAULT now(),
        CONSTRAINT uq_ai_providers_key UNIQUE (provider_key),
        CONSTRAINT ck_ai_providers_status CHECK (status IN ('active', 'disabled')),
        CONSTRAINT ck_ai_providers_timeout CHECK (timeout_seconds > 0),
        CONSTRAINT ck_ai_providers_retries CHECK (max_retries BETWEEN 0 AND 5)
    )
    """,
    "CREATE INDEX IF NOT EXISTS ix_ai_providers_status ON ai_providers (status)",
    # 模型：业务别名 → (来源, 上游模型名)；能力与结构化方式跟随模型声明
    """
    CREATE TABLE IF NOT EXISTS ai_models (
        id                         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        alias                      varchar(64)  NOT NULL,
        provider_id                integer      NOT NULL REFERENCES ai_providers (id) ON DELETE RESTRICT,
        upstream_name              varchar(128) NOT NULL,
        supports_text              boolean      NOT NULL DEFAULT true,
        supports_vision            boolean      NOT NULL DEFAULT false,
        supports_tools             boolean      NOT NULL DEFAULT false,
        supports_structured_output boolean      NOT NULL DEFAULT true,
        structured_method          varchar(24)  NOT NULL DEFAULT 'json_schema',
        timeout_seconds            numeric(6,1) NULL,
        extra_body                 jsonb        NOT NULL DEFAULT '{}'::jsonb,
        params                     jsonb        NOT NULL DEFAULT '{}'::jsonb,
        selectable_for_chat        boolean      NOT NULL DEFAULT true,
        status                     varchar(16)  NOT NULL DEFAULT 'active',
        sort_order                 integer      NOT NULL DEFAULT 0,
        remark                     varchar(200) NOT NULL DEFAULT '',
        created_at                 timestamp    NOT NULL DEFAULT now(),
        updated_at                 timestamp    NOT NULL DEFAULT now(),
        CONSTRAINT uq_ai_models_alias UNIQUE (alias),
        CONSTRAINT ck_ai_models_status CHECK (status IN ('active', 'disabled')),
        CONSTRAINT ck_ai_models_method CHECK (structured_method IN ('json_schema', 'function_calling', 'json_mode')),
        CONSTRAINT ck_ai_models_timeout CHECK (timeout_seconds IS NULL OR timeout_seconds > 0)
    )
    """,
    "CREATE INDEX IF NOT EXISTS ix_ai_models_provider ON ai_models (provider_id, status)",
    # 功能路由：一个功能点只认一个模型别名（单模型，不做主备降级）
    """
    CREATE TABLE IF NOT EXISTS ai_feature_routes (
        id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        feature_key     varchar(64)  NOT NULL,
        model_alias     varchar(64)  NOT NULL,
        timeout_seconds numeric(6,1) NULL,
        params_override jsonb        NOT NULL DEFAULT '{}'::jsonb,
        enabled         boolean      NOT NULL DEFAULT true,
        remark          varchar(200) NOT NULL DEFAULT '',
        created_at      timestamp    NOT NULL DEFAULT now(),
        updated_at      timestamp    NOT NULL DEFAULT now(),
        CONSTRAINT uq_ai_feature_routes_key UNIQUE (feature_key),
        CONSTRAINT ck_ai_feature_routes_timeout CHECK (timeout_seconds IS NULL OR timeout_seconds > 0)
    )
    """,
]

COMMENTS = [
    "COMMENT ON TABLE ai_providers IS 'AI 模型来源（一个 base_url + 一套凭据；可多来源供不同功能点分别使用）'",
    "COMMENT ON COLUMN ai_providers.id IS '主键'",
    "COMMENT ON COLUMN ai_providers.provider_key IS '来源短标识（唯一，如 maas-default），供审计与排查引用'",
    "COMMENT ON COLUMN ai_providers.name IS '来源显示名'",
    "COMMENT ON COLUMN ai_providers.base_url IS 'OpenAI 兼容接口地址（含 /v1 之类的兼容路径，不含密钥）'",
    "COMMENT ON COLUMN ai_providers.api_key_env IS '密钥所在环境变量名；未配置加密密钥时从该变量读取'",
    "COMMENT ON COLUMN ai_providers.api_key_cipher IS '管理页写入的加密密钥（SECRET_KEY 派生密钥加密）；为空表示走 api_key_env'",
    "COMMENT ON COLUMN ai_providers.timeout_seconds IS '来源默认读超时（秒）；模型与调用点可覆盖'",
    "COMMENT ON COLUMN ai_providers.max_retries IS '来源默认重试次数（0~5）'",
    "COMMENT ON COLUMN ai_providers.extra_headers IS '附加请求头 JSON（如自定义鉴权头，不含密钥）'",
    "COMMENT ON COLUMN ai_providers.status IS '状态：active / disabled；停用后不参与解析'",
    "COMMENT ON COLUMN ai_providers.remark IS '备注（额度、计费口径等人工说明）'",
    "COMMENT ON COLUMN ai_providers.updated_by IS '最近维护人 user_id（逻辑外键）'",
    "COMMENT ON COLUMN ai_providers.created_at IS '创建时间'",
    "COMMENT ON COLUMN ai_providers.updated_at IS '更新时间（保存即生效的版本判断依据）'",

    "COMMENT ON TABLE ai_models IS 'AI 模型清单（业务别名 + 来源 + 上游模型名 + 能力声明）'",
    "COMMENT ON COLUMN ai_models.id IS '主键'",
    "COMMENT ON COLUMN ai_models.alias IS '业务别名（唯一）；代码、会话、报告与前端下拉只认别名'",
    "COMMENT ON COLUMN ai_models.provider_id IS '所属来源 FK → ai_providers.id，RESTRICT（先解绑才能删来源）'",
    "COMMENT ON COLUMN ai_models.upstream_name IS '上游模型名（真正发给服务商的 model 字段），可与别名不同'",
    "COMMENT ON COLUMN ai_models.supports_text IS '是否支持纯文本对话'",
    "COMMENT ON COLUMN ai_models.supports_vision IS '是否支持图片输入（图片以 data URL 传入）'",
    "COMMENT ON COLUMN ai_models.supports_tools IS '是否支持工具调用；agent.chat 路由必须为 true'",
    "COMMENT ON COLUMN ai_models.supports_structured_output IS '是否支持结构化输出；导入/报告/建议/技能解析路由必须为 true'",
    "COMMENT ON COLUMN ai_models.structured_method IS '结构化输出方式：json_schema / function_calling / json_mode'",
    "COMMENT ON COLUMN ai_models.timeout_seconds IS '模型级读超时（秒，可空；空则用来源默认）'",
    "COMMENT ON COLUMN ai_models.extra_body IS '附加请求体 JSON（如 {\"enable_thinking\": false}）；与路由 params_override 合并'",
    "COMMENT ON COLUMN ai_models.params IS '通用参数 JSON（如 temperature / max_tokens）；路由可覆盖'",
    "COMMENT ON COLUMN ai_models.selectable_for_chat IS '是否出现在 AI 助手页的模型下拉'",
    "COMMENT ON COLUMN ai_models.status IS '状态：active / disabled；停用后路由不可引用'",
    "COMMENT ON COLUMN ai_models.sort_order IS '下拉与列表排序'",
    "COMMENT ON COLUMN ai_models.remark IS '备注（实测结论、能力限制等人工说明）'",
    "COMMENT ON COLUMN ai_models.created_at IS '创建时间'",
    "COMMENT ON COLUMN ai_models.updated_at IS '更新时间（保存即生效的版本判断依据）'",

    "COMMENT ON TABLE ai_feature_routes IS 'AI 功能路由（一个功能点配一个模型别名，单模型不降级）'",
    "COMMENT ON COLUMN ai_feature_routes.id IS '主键'",
    "COMMENT ON COLUMN ai_feature_routes.feature_key IS '功能键（唯一），取值由代码常量固定：agent.chat / agent.skill_parse / import.text / import.vision / report.weekly / report.monthly / advice.daily'",
    "COMMENT ON COLUMN ai_feature_routes.model_alias IS '目标模型别名（逻辑关联 ai_models.alias，保存时由应用校验存在且启用）'",
    "COMMENT ON COLUMN ai_feature_routes.timeout_seconds IS '该功能点的读超时（秒，可空；空则依次用模型、来源默认）'",
    "COMMENT ON COLUMN ai_feature_routes.params_override IS '覆盖模型 params / extra_body 的 JSON（如报告关思考写 extra_body.enable_thinking=false）'",
    "COMMENT ON COLUMN ai_feature_routes.enabled IS '是否启用；停用时回落 .env 与代码默认'",
    "COMMENT ON COLUMN ai_feature_routes.remark IS '备注（该功能点选型原因等）'",
    "COMMENT ON COLUMN ai_feature_routes.created_at IS '创建时间'",
    "COMMENT ON COLUMN ai_feature_routes.updated_at IS '更新时间（保存即生效的版本判断依据）'",
]


def main() -> None:
    with engine.begin() as conn:
        for sql in DDL:
            conn.execute(text(sql))
        for sql in COMMENTS:
            conn.execute(text(sql))
        rows = conn.execute(text(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = 'public' AND table_name IN "
            "('ai_providers', 'ai_models', 'ai_feature_routes') ORDER BY table_name"
        )).fetchall()
        print(f"AI 模型配置表迁移完成：{[r[0] for r in rows]}")
        print("下一步：python scripts/seed_ai_config.py（按 .env 写入初始来源、模型与路由）")


if __name__ == "__main__":
    main()
