"""定时任务表迁移（幂等）：scheduled_jobs / job_runs 两张表、索引、中文 COMMENT 与默认任务。

用法：
    python scripts/migrate_scheduler.py

说明：只新增两张表，不改动已有表；可重复执行。默认任务（周报/月报）也在此补齐，
应用启动时同样会做一次幂等补齐。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import text

from database import SessionLocal, engine

DDL = [
    """
    CREATE TABLE IF NOT EXISTS scheduled_jobs (
        id                    integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        job_key               varchar(64)  NOT NULL,
        name                  varchar(64)  NOT NULL,
        trigger_type          varchar(16)  NOT NULL,
        trigger_expr          varchar(128) NOT NULL,
        timezone              varchar(48)  NOT NULL DEFAULT 'Asia/Shanghai',
        params                jsonb        NOT NULL DEFAULT '{}'::jsonb,
        enabled               boolean      NOT NULL DEFAULT true,
        misfire_grace_seconds integer      NULL,
        next_run_at           timestamp    NULL,
        last_run_at           timestamp    NULL,
        last_status           varchar(16)  NULL,
        last_message          varchar(500) NULL,
        last_duration_ms      integer      NOT NULL DEFAULT 0,
        run_count             integer      NOT NULL DEFAULT 0,
        created_at            timestamp    NOT NULL DEFAULT now(),
        updated_at            timestamp    NOT NULL DEFAULT now(),
        CONSTRAINT ck_scheduled_jobs_trigger CHECK (trigger_type IN ('cron', 'date', 'interval'))
    )
    """,
    "CREATE INDEX IF NOT EXISTS ix_scheduled_jobs_key ON scheduled_jobs (job_key)",
    """
    CREATE TABLE IF NOT EXISTS job_runs (
        id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        job_id      integer      NULL REFERENCES scheduled_jobs (id) ON DELETE CASCADE,
        job_key     varchar(64)  NOT NULL,
        source      varchar(16)  NOT NULL,
        status      varchar(16)  NOT NULL,
        started_at  timestamp    NOT NULL,
        finished_at timestamp    NULL,
        duration_ms integer      NOT NULL DEFAULT 0,
        message     varchar(500) NULL,
        detail      jsonb        NULL,
        created_at  timestamp    NOT NULL DEFAULT now(),
        CONSTRAINT ck_job_runs_status CHECK (status IN ('running', 'success', 'failed', 'skipped')),
        CONSTRAINT ck_job_runs_source CHECK (source IN ('schedule', 'manual', 'cli'))
    )
    """,
    "CREATE INDEX IF NOT EXISTS ix_job_runs_job ON job_runs (job_id, started_at)",
]

COMMENTS = [
    "COMMENT ON TABLE scheduled_jobs IS '定时任务定义（job_key 指向代码注册表；表达式为本表唯一事实源）'",
    "COMMENT ON COLUMN scheduled_jobs.id IS '主键'",
    "COMMENT ON COLUMN scheduled_jobs.job_key IS '任务键，对应 app/modules/scheduler/registry.py'",
    "COMMENT ON COLUMN scheduled_jobs.name IS '任务显示名'",
    "COMMENT ON COLUMN scheduled_jobs.trigger_type IS '触发类型：cron / date / interval'",
    "COMMENT ON COLUMN scheduled_jobs.trigger_expr IS '触发表达式（cron 五段式 / interval 如 10m / date 如 2026-11-20 15:40）'",
    "COMMENT ON COLUMN scheduled_jobs.timezone IS '触发时区（默认 Asia/Shanghai，避免服务器 UTC 时区错位）'",
    "COMMENT ON COLUMN scheduled_jobs.params IS '任务参数 JSON（结构由 registry 的参数 schema 约束）'",
    "COMMENT ON COLUMN scheduled_jobs.enabled IS '是否启用；禁用时不注册内存作业'",
    "COMMENT ON COLUMN scheduled_jobs.misfire_grace_seconds IS '错过宽限秒数；可空，空则用全局 settings.scheduler_misfire_grace_seconds'",
    "COMMENT ON COLUMN scheduled_jobs.next_run_at IS '下次触发时间（由调度器回写，服务未运行时为空）'",
    "COMMENT ON COLUMN scheduled_jobs.last_run_at IS '最近一次执行时间'",
    "COMMENT ON COLUMN scheduled_jobs.last_status IS '最近一次结果：running / success / failed / skipped'",
    "COMMENT ON COLUMN scheduled_jobs.last_message IS '最近一次结果摘要或失败原因'",
    "COMMENT ON COLUMN scheduled_jobs.last_duration_ms IS '最近一次耗时 ms'",
    "COMMENT ON COLUMN scheduled_jobs.run_count IS '累计执行次数（含手动）'",
    "COMMENT ON COLUMN scheduled_jobs.created_at IS '创建时间'",
    "COMMENT ON COLUMN scheduled_jobs.updated_at IS '更新时间'",
    "COMMENT ON TABLE job_runs IS '定时任务执行记录（触发来源、结果、耗时与摘要）'",
    "COMMENT ON COLUMN job_runs.id IS '主键'",
    "COMMENT ON COLUMN job_runs.job_id IS '所属任务 FK，可空（命令行执行未挂任务定义时为空）'",
    "COMMENT ON COLUMN job_runs.job_key IS '任务键'",
    "COMMENT ON COLUMN job_runs.source IS '触发来源：schedule / manual / cli'",
    "COMMENT ON COLUMN job_runs.status IS '结果：running / success / failed / skipped'",
    "COMMENT ON COLUMN job_runs.started_at IS '开始时间'",
    "COMMENT ON COLUMN job_runs.finished_at IS '结束时间'",
    "COMMENT ON COLUMN job_runs.duration_ms IS '耗时 ms'",
    "COMMENT ON COLUMN job_runs.message IS '结果摘要或失败原因'",
    "COMMENT ON COLUMN job_runs.detail IS '执行明细 JSON（如生成份数、失败条目）'",
    "COMMENT ON COLUMN job_runs.created_at IS '创建时间'",
]


def main() -> None:
    with engine.begin() as conn:
        for sql in DDL:
            conn.execute(text(sql))
        for sql in COMMENTS:
            conn.execute(text(sql))

    from app.modules.scheduler import service

    db = SessionLocal()
    try:
        created = service.seed_defaults(db)
    finally:
        db.close()
    print(f"定时任务表迁移完成，补默认任务 {created} 条")


if __name__ == "__main__":
    main()
