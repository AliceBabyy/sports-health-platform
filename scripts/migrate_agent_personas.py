"""V2.4 多角色表迁移（幂等）：agent_personas / agent_persona_versions + 会话角色绑定列。

用法：
    python scripts/migrate_agent_personas.py

说明：只新增两张角色表、索引、会话两列与约束，并刷新 COMMENT；不改动已有业务数据，可重复执行。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import text

from database import engine

DDL = [
    """
    CREATE TABLE IF NOT EXISTS agent_personas (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        scope varchar(16) NOT NULL,
        owner_user_id integer NULL REFERENCES users (id) ON DELETE CASCADE,
        persona_key varchar(48) NOT NULL,
        name varchar(48) NOT NULL,
        description varchar(200) NOT NULL DEFAULT '',
        status varchar(16) NOT NULL DEFAULT 'active',
        sort_order integer NOT NULL DEFAULT 0,
        current_version_no integer NULL,
        created_at timestamp NOT NULL DEFAULT now(),
        updated_at timestamp NOT NULL DEFAULT now(),
        CONSTRAINT ck_agent_personas_scope CHECK (scope IN ('system', 'user')),
        CONSTRAINT ck_agent_personas_owner CHECK (
            (scope = 'system' AND owner_user_id IS NULL)
            OR (scope = 'user' AND owner_user_id IS NOT NULL)
        ),
        CONSTRAINT ck_agent_personas_status CHECK (status IN ('active', 'disabled'))
    )
    """,
    """
    CREATE UNIQUE INDEX IF NOT EXISTS uq_agent_personas_system_key
        ON agent_personas (persona_key) WHERE scope = 'system'
    """,
    """
    CREATE UNIQUE INDEX IF NOT EXISTS uq_agent_personas_user_key
        ON agent_personas (owner_user_id, persona_key) WHERE scope = 'user'
    """,
    """
    CREATE INDEX IF NOT EXISTS ix_agent_personas_list
        ON agent_personas (scope, status, sort_order)
    """,
    """
    CREATE TABLE IF NOT EXISTS agent_persona_versions (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        persona_id integer NOT NULL REFERENCES agent_personas (id) ON DELETE CASCADE,
        version_no integer NOT NULL,
        definition jsonb NOT NULL,
        definition_hash varchar(64) NOT NULL DEFAULT '',
        validation jsonb NULL,
        created_by integer NULL,
        published_at timestamp NULL,
        created_at timestamp NOT NULL DEFAULT now()
    )
    """,
    """
    CREATE UNIQUE INDEX IF NOT EXISTS uq_agent_persona_versions_no
        ON agent_persona_versions (persona_id, version_no)
    """,
    """
    ALTER TABLE agent_conversations
        ADD COLUMN IF NOT EXISTS persona_id integer NULL REFERENCES agent_personas (id)
    """,
    """
    ALTER TABLE agent_conversations
        ADD COLUMN IF NOT EXISTS persona_version_no integer NULL
    """,
    """
    ALTER TABLE agent_conversations DROP CONSTRAINT IF EXISTS ck_agent_conversations_persona
    """,
    """
    ALTER TABLE agent_conversations ADD CONSTRAINT ck_agent_conversations_persona
        CHECK ((persona_id IS NULL) = (persona_version_no IS NULL))
    """,
]

COMMENTS = [
    ("TABLE", "agent_conversations",
     "AI Agent 会话（元数据 + LangGraph thread_id + 角色绑定；消息由 checkpointer 管理）"),
    ("COLUMN", "agent_conversations.persona_id",
     "角色会话绑定的角色 FK；普通会话为空，创建后不可切换"),
    ("COLUMN", "agent_conversations.persona_version_no",
     "创建会话时绑定的角色版本号，保证历史会话不随角色改版漂移"),
    ("TABLE", "agent_personas", "AI 角色（平台内置只读 + 用户私有自定义提示词角色）"),
    ("COLUMN", "agent_personas.scope", "归属：system / user"),
    ("COLUMN", "agent_personas.owner_user_id", "用户角色归属；平台内置角色为空"),
    ("COLUMN", "agent_personas.persona_key", "稳定键，供种子幂等与后续工具授权使用"),
    ("COLUMN", "agent_personas.name", "角色显示名"),
    ("COLUMN", "agent_personas.description", "角色定位，供列表展示与人设段渲染"),
    ("COLUMN", "agent_personas.status", "状态：active / disabled（停用后不可新建角色会话，已有会话仍可继续）"),
    ("COLUMN", "agent_personas.sort_order", "平台角色排序；用户角色不参与"),
    ("COLUMN", "agent_personas.current_version_no", "当前生效版本号；未发布为空"),
    ("COLUMN", "agent_personas.created_at", "创建时间"),
    ("COLUMN", "agent_personas.updated_at", "更新时间"),
    ("TABLE", "agent_persona_versions", "AI 角色版本（人设提示词定义与发布快照）"),
    ("COLUMN", "agent_persona_versions.persona_id", "角色 FK，删除角色时级联删除"),
    ("COLUMN", "agent_persona_versions.version_no", "版本号，从 1 递增"),
    ("COLUMN", "agent_persona_versions.definition", "角色定义 JSON：{schema_version, prompt}"),
    ("COLUMN", "agent_persona_versions.definition_hash", "定义 SHA-256，便于审计"),
    ("COLUMN", "agent_persona_versions.validation", "最近一次校验结果（errors/warnings）"),
    ("COLUMN", "agent_persona_versions.created_by", "创建人 user_id"),
    ("COLUMN", "agent_persona_versions.published_at", "生效时间；NULL 表示草稿"),
    ("COLUMN", "agent_persona_versions.created_at", "创建时间"),
]


def main() -> None:
    with engine.begin() as conn:
        for sql in DDL:
            conn.execute(text(sql))
        for kind, target, comment in COMMENTS:
            conn.execute(text(f"COMMENT ON {kind} {target} IS :comment"), {"comment": comment})
    print("agent_personas 两表、会话角色绑定列与注释已就绪。")


if __name__ == "__main__":
    main()
