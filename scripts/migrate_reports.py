"""报告表迁移（幂等）：reports 表、唯一约束、索引与中文 COMMENT。

用法：
    python scripts/migrate_reports.py

说明：只新增一张表，不改动已有表；可重复执行。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import text

from database import engine

DDL = [
    """
    CREATE TABLE IF NOT EXISTS reports (
        id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id         integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
        period_type     varchar(8)   NOT NULL,
        period_start    date         NOT NULL,
        period_end      date         NOT NULL,
        status          varchar(16)  NOT NULL DEFAULT 'generating',
        mode            varchar(16)  NOT NULL DEFAULT 'ai',
        headline        varchar(64)  NULL,
        facts           jsonb        NOT NULL,
        narrative       jsonb        NULL,
        data_hash       varchar(64)  NOT NULL DEFAULT '',
        model_name      varchar(64)  NULL,
        prompt_version  varchar(48)  NULL,
        generation_ms   integer      NOT NULL DEFAULT 0,
        attempts        integer      NOT NULL DEFAULT 0,
        error_code      varchar(48)  NULL,
        error_message   varchar(500) NULL,
        generated_at    timestamp    NULL,
        deleted_at      timestamp    NULL,
        created_at      timestamp    NOT NULL DEFAULT now(),
        updated_at      timestamp    NOT NULL DEFAULT now(),
        CONSTRAINT uq_reports_user_period UNIQUE (user_id, period_type, period_start),
        CONSTRAINT ck_reports_type CHECK (period_type IN ('weekly', 'monthly')),
        CONSTRAINT ck_reports_status CHECK (status IN ('generating', 'ready', 'failed', 'deleted')),
        CONSTRAINT ck_reports_mode CHECK (mode IN ('ai', 'rule'))
    )
    """,
    "CREATE INDEX IF NOT EXISTS ix_reports_user_period ON reports (user_id, period_type, period_start DESC)",
]

COMMENTS = [
    "COMMENT ON TABLE reports IS 'AI 运动报告（周报/月报；事实快照 + 叙事 + 生成元信息）'",
    "COMMENT ON COLUMN reports.id IS '主键'",
    "COMMENT ON COLUMN reports.user_id IS '用户 FK，删除账号时级联删除'",
    "COMMENT ON COLUMN reports.period_type IS '周期类型：weekly（周报）/ monthly（月报）'",
    "COMMENT ON COLUMN reports.period_start IS '周期起始日（周报=周一，月报=1 日）'",
    "COMMENT ON COLUMN reports.period_end IS '周期结束日（周报=周日，月报=月末）'",
    "COMMENT ON COLUMN reports.status IS '状态：generating / ready / failed / deleted'",
    "COMMENT ON COLUMN reports.mode IS '生成方式：ai（模型叙事）/ rule（无数据规则文案，不调模型）'",
    "COMMENT ON COLUMN reports.headline IS '一句话主题（列表展示冗余）'",
    "COMMENT ON COLUMN reports.facts IS '生成时的事实快照（确定性计算，含指标字典）'",
    "COMMENT ON COLUMN reports.narrative IS 'AI 结构化叙事（headline/summary/highlights 等）'",
    "COMMENT ON COLUMN reports.data_hash IS 'facts 的 SHA-256，用于过期检测'",
    "COMMENT ON COLUMN reports.model_name IS '生成所用模型'",
    "COMMENT ON COLUMN reports.prompt_version IS '提示词版本 ID（如 weekly_report.v1）'",
    "COMMENT ON COLUMN reports.generation_ms IS '生成耗时 ms'",
    "COMMENT ON COLUMN reports.attempts IS '自动生成尝试次数（定时任务重试上限用）'",
    "COMMENT ON COLUMN reports.error_code IS '失败错误码'",
    "COMMENT ON COLUMN reports.error_message IS '失败信息'",
    "COMMENT ON COLUMN reports.generated_at IS '生成完成时间'",
    "COMMENT ON COLUMN reports.deleted_at IS '软删除时间；NULL 表示未删除'",
    "COMMENT ON COLUMN reports.created_at IS '创建时间'",
    "COMMENT ON COLUMN reports.updated_at IS '更新时间（ORM onupdate 自动刷新；也用于判断 generating 是否卡死）'",
]


def main() -> None:
    with engine.begin() as conn:
        for sql in DDL:
            conn.execute(text(sql))
        for sql in COMMENTS:
            conn.execute(text(sql))
    print("reports 表迁移完成")


if __name__ == "__main__":
    main()
