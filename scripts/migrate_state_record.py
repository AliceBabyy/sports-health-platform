# -*- coding: utf-8 -*-
# 2026-11 状态记录迁移（幂等，可重复执行）：
# 新建 appetite_record / myalgia_record / inflammation_record 三张按天记录表。
# 统一字段：id / user_id（FK 级联）/ date（同类一天一行）/ star（1~5 可空）/ remark（可空）/
#           created_at / updated_at；不套运动记录契约（无计划态、起止时间、心率、热量等）。
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import psycopg2  # noqa: E402

DSN = "postgresql://postgres:123456@127.0.0.1:5432/sports-health-platform"

TABLES = {
    "appetite_record": ("uq_appetite_user_date", "ix_appetite_record_user_date_id", "食欲状态记录（按天，每类每天一行）"),
    "myalgia_record": ("uq_myalgia_user_date", "ix_myalgia_record_user_date_id", "肌肉疼痛状态记录（按天，每类每天一行）"),
    "inflammation_record": ("uq_inflammation_user_date", "ix_inflammation_record_user_date_id", "炎症状态记录（按天，每类每天一行）"),
}


def _create_table(cur, table: str, unique: str, idx: str, comment: str) -> None:
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS "{table}" (
            id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id    integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
            date       date         NOT NULL,
            star       smallint     NULL,
            remark     varchar(255) NULL,
            created_at timestamp    NOT NULL DEFAULT now(),
            updated_at timestamp    NOT NULL DEFAULT now(),
            CONSTRAINT {unique} UNIQUE (user_id, date)
        )
        """
    )
    cur.execute(f'CREATE INDEX IF NOT EXISTS ix_{table}_user_id ON "{table}" (user_id)')
    cur.execute(f'CREATE INDEX IF NOT EXISTS {idx} ON "{table}" (user_id, date, id)')
    cur.execute(f'COMMENT ON TABLE "{table}" IS %s', (comment,))
    cur.execute(f'COMMENT ON COLUMN "{table}".id IS %s', ("主键",))
    cur.execute(f'COMMENT ON COLUMN "{table}".user_id IS %s', ("用户 FK，删除账号时级联删除",))
    cur.execute(f'COMMENT ON COLUMN "{table}".date IS %s', ("记录日期（同类一天一行）",))
    cur.execute(f'COMMENT ON COLUMN "{table}".star IS %s', ("星级 1~5，可空",))
    cur.execute(f'COMMENT ON COLUMN "{table}".remark IS %s', ("描述",))
    cur.execute(f'COMMENT ON COLUMN "{table}".created_at IS %s', ("创建时间",))
    cur.execute(f'COMMENT ON COLUMN "{table}".updated_at IS %s', ("更新时间（ORM onupdate 自动刷新）",))


def run() -> None:
    conn = psycopg2.connect(DSN)
    conn.autocommit = True
    with conn.cursor() as cur:
        for table, (unique, idx, comment) in TABLES.items():
            _create_table(cur, table, unique, idx, comment)
            print(f"完成：{table} 表结构与注释已就绪。")
    conn.close()


if __name__ == "__main__":
    run()
