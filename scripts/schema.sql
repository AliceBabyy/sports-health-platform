);

-- ---------- 6. 生理周期 ----------
-- 四档状态按周期段内日序及疼痛实时推算；日历浅蓝绿/绿/黄/粉配色与窄屏状态短名仅在前端维护，不作为数据库字段。
-- period_setting 语义为「参考值」：不随记录变化，只用于当前段、预测段、补推段与未填结束日的记录。
CREATE TABLE period_setting (
    user_id       integer   NOT NULL PRIMARY KEY REFERENCES users (id),
    cycle_length  integer   NOT NULL DEFAULT 28,
    period_length integer   NOT NULL DEFAULT 5,
    updated_at    timestamp NOT NULL DEFAULT now()
);

CREATE TABLE period_records (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer NOT NULL,
    start_date date    NOT NULL,                     -- 月经开始日（分段依据）；应用层校验同用户不重复、相邻首日间隔下限
    end_date   date    NULL,                         -- 结束日（可后补；经期长度 = 结束 - 开始 + 1，不落库）
    created_at timestamp NOT NULL DEFAULT now()
);
CREATE INDEX ix_period_records_user_id ON period_records (user_id);

CREATE TABLE period_logs (
    id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer      NOT NULL,
    log_date   date         NOT NULL,
    pain_level smallint     NULL,                    -- 0无/1轻/2中/3重；仅经期可填，非经期为 NULL
    note       varchar(255) NULL,                    -- 当日 note
    period_id  integer      NULL REFERENCES period_records (id) ON DELETE SET NULL,  -- 归属月经记录；非经期为 NULL
    created_at timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_period_log_user_date UNIQUE (user_id, log_date)
);
CREATE INDEX ix_period_logs_user_id ON period_logs (user_id);
CREATE INDEX ix_period_logs_period_id ON period_logs (period_id);

