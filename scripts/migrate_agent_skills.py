def main() -> None:
    with engine.begin() as conn:
        for sql in DDL:
            conn.execute(text(sql))
        violations = conn.execute(text(
            """
            SELECT id, scope, kind FROM agent_skills
            WHERE NOT (
                (scope = 'system' AND kind IN ('code', 'declarative'))
                OR (scope = 'user' AND kind = 'prompt')
            )
            """
        )).all()
        if violations:
            detail = "、".join(f"id={row.id}({row.scope}/{row.kind})" for row in violations)
            raise RuntimeError(
                "存在不符合 scope-kind 契约的技能，已停止迁移：" + detail +
                "；请先确认或迁移这些技能，再重新执行。"
            )
        conn.execute(text(SCOPE_KIND_SQL))
        for kind, target, comment in COMMENTS:
            conn.execute(text(f"COMMENT ON {kind} {target} IS :comment"), {"comment": comment})
    print("agent_skills 三表、scope-kind 约束与注释已就绪。")


if __name__ == "__main__":
    main()
