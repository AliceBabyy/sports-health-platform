-- ---------- 7. AI Agent（角色、会话元数据；消息由 checkpointer 框架表管理） ----------
-- V2.4 多角色：平台内置 2 个角色（营养师 / 电子私教）+ 用户私有提示词角色；角色只影响人设提示词
CREATE TABLE agent_personas (
    id                  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope               varchar(16)  NOT NULL,              -- system / user
    owner_user_id       integer      NULL REFERENCES users (id) ON DELETE CASCADE,
    persona_key         varchar(48)  NOT NULL,              -- 稳定键：nutrition / e_trainer / 用户自定义
    name                varchar(48)  NOT NULL,
    description         varchar(200) NOT NULL DEFAULT '',
    status              varchar(16)  NOT NULL DEFAULT 'active',   -- active / disabled
    sort_order          integer      NOT NULL DEFAULT 0,
    current_version_no  integer      NULL,
    tool_grants         jsonb        NULL,                  -- 角色可用工具白名单；NULL=平台默认
    skill_grants        jsonb        NULL,                  -- 角色可用平台技能白名单；NULL=全部
    created_at          timestamp    NOT NULL DEFAULT now(),
    updated_at          timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT ck_agent_personas_scope CHECK (scope IN ('system', 'user')),
    CONSTRAINT ck_agent_personas_owner CHECK (
        (scope = 'system' AND owner_user_id IS NULL)
        OR (scope = 'user' AND owner_user_id IS NOT NULL)
    ),
    CONSTRAINT ck_agent_personas_status CHECK (status IN ('active', 'disabled'))
);
CREATE UNIQUE INDEX uq_agent_personas_system_key ON agent_personas (persona_key) WHERE scope = 'system';
CREATE UNIQUE INDEX uq_agent_personas_user_key ON agent_personas (owner_user_id, persona_key) WHERE scope = 'user';
CREATE INDEX ix_agent_personas_list ON agent_personas (scope, status, sort_order);

CREATE TABLE agent_persona_versions (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_id      integer      NOT NULL REFERENCES agent_personas (id) ON DELETE CASCADE,
    version_no      integer      NOT NULL,
    definition      jsonb        NOT NULL,                  -- {schema_version:1, prompt}
    definition_hash varchar(64)  NOT NULL DEFAULT '',
    validation      jsonb        NULL,
    created_by      integer      NULL,
    published_at    timestamp    NULL,
    created_at      timestamp    NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_agent_persona_versions_no ON agent_persona_versions (persona_id, version_no);

CREATE TABLE agent_conversations (
    id                  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title               varchar(64)  NOT NULL DEFAULT '新会话',
    model_name          varchar(64)  NULL,                  -- 会话级模型（可空，用默认模型）
    thread_id           uuid         NOT NULL UNIQUE,        -- LangGraph 线程 ID（checkpointer 键）
    persona_id          integer      NULL REFERENCES agent_personas (id),  -- 角色会话绑定；普通会话为空
    persona_version_no  integer      NULL,                  -- 创建时绑定的角色版本号
    last_message_at     timestamp    NULL,                  -- 最近消息时间（列表排序冗余）
    pinned              boolean      NOT NULL DEFAULT false, -- 是否置顶；置顶排在最前
    created_at          timestamp    NOT NULL DEFAULT now(),
    updated_at          timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT ck_agent_conversations_persona CHECK ((persona_id IS NULL) = (persona_version_no IS NULL))
);
CREATE INDEX ix_agent_conversations_user_last ON agent_conversations (user_id, last_message_at DESC);
CREATE INDEX ix_agent_conversations_user_pinned_last ON agent_conversations (user_id, pinned DESC, last_message_at DESC);

-- V2.4 AI 技能：平台技能（只读）+ 用户私有自定义技能（声明式 DSL / 提示词）
CREATE TABLE agent_skills (
    id                  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope               varchar(16)  NOT NULL,              -- system / user
    owner_user_id       integer      NULL REFERENCES users (id) ON DELETE CASCADE,
    skill_key           varchar(48)  NOT NULL,              -- 工具名为 skill_<key>
    name                varchar(48)  NOT NULL,
    description         varchar(200) NOT NULL DEFAULT '',
    kind                varchar(16)  NOT NULL DEFAULT 'prompt',     -- system: code/declarative/prompt; user: prompt
    category            varchar(16)  NOT NULL DEFAULT 'custom',       -- body / swim / fitness / dance / profile / custom
    status              varchar(16)  NOT NULL DEFAULT 'draft',        -- draft / active / disabled / archived
    slash_alias         varchar(24)  NULL,
    current_version_no  integer      NULL,
    created_at          timestamp    NOT NULL DEFAULT now(),
    updated_at          timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT ck_agent_skills_scope CHECK (scope IN ('system', 'user')),
    CONSTRAINT ck_agent_skills_scope_kind CHECK (
        (scope = 'system' AND kind IN ('code', 'declarative', 'prompt'))
        OR (scope = 'user' AND kind = 'prompt')
    ),
    CONSTRAINT ck_agent_skills_status CHECK (status IN ('draft', 'active', 'disabled', 'archived'))
);
CREATE UNIQUE INDEX uq_agent_skills_system_key ON agent_skills (skill_key) WHERE scope = 'system';
CREATE UNIQUE INDEX uq_agent_skills_user_key ON agent_skills (owner_user_id, skill_key) WHERE scope = 'user';
CREATE UNIQUE INDEX uq_agent_skills_user_alias ON agent_skills (owner_user_id, slash_alias)
    WHERE scope = 'user' AND slash_alias IS NOT NULL;
CREATE INDEX ix_agent_skills_owner ON agent_skills (owner_user_id);

CREATE TABLE agent_skill_versions (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id        integer      NOT NULL REFERENCES agent_skills (id) ON DELETE CASCADE,
    version_no      integer      NOT NULL,
    definition      jsonb        NOT NULL,
    definition_hash varchar(64)  NOT NULL DEFAULT '',
    validation      jsonb        NULL,
    created_by      integer      NULL,
    published_at    timestamp    NULL,
    created_at      timestamp    NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_agent_skill_versions_skill_no ON agent_skill_versions (skill_id, version_no);

CREATE TABLE agent_skill_runs (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id        integer      NOT NULL REFERENCES agent_skills (id) ON DELETE CASCADE,
    version_no      integer      NOT NULL,
    user_id         integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    conversation_id integer      NULL,
    trigger         varchar(16)  NOT NULL DEFAULT 'model',   -- slash / model / test
    status          varchar(16)  NOT NULL,
    error_code      varchar(48)  NULL,
    error_message   varchar(500) NULL,
    args            jsonb        NULL,
    parse           jsonb        NULL,
    sample_size     integer      NOT NULL DEFAULT 0,
    duration_ms     integer      NOT NULL DEFAULT 0,
    created_at      timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX ix_agent_skill_runs_skill_created ON agent_skill_runs (skill_id, created_at DESC);
CREATE INDEX ix_agent_skill_runs_user_created ON agent_skill_runs (user_id, created_at DESC);

-- ---------- 8. AI 运动报告（周报/月报：事实快照 + 叙事 + 生成元信息；软删除） ----------
CREATE TABLE reports (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    period_type     varchar(8)   NOT NULL,                  -- weekly / monthly
    period_start    date         NOT NULL,                  -- 周报=周一，月报=1 日
    period_end      date         NOT NULL,                  -- 周报=周日，月报=月末
    status          varchar(16)  NOT NULL DEFAULT 'generating',  -- generating / ready / failed / deleted
    mode            varchar(16)  NOT NULL DEFAULT 'ai',          -- ai / rule（无数据规则文案）
    headline        varchar(64)  NULL,                      -- 一句话主题（列表展示冗余）
    facts           jsonb        NOT NULL,                  -- 事实快照（确定性计算）
    narrative       jsonb        NULL,                      -- AI 结构化叙事
    data_hash       varchar(64)  NOT NULL DEFAULT '',       -- facts 的 SHA-256（过期检测）
    model_name      varchar(64)  NULL,
    prompt_version  varchar(48)  NULL,
    generation_ms   integer      NOT NULL DEFAULT 0,
    attempts        integer      NOT NULL DEFAULT 0,        -- 自动生成尝试次数（重试上限）
    error_code      varchar(48)  NULL,
    error_message   varchar(500) NULL,
    generated_at    timestamp    NULL,
    deleted_at      timestamp    NULL,                      -- 软删除时间；NULL 表示未删除
    created_at      timestamp    NOT NULL DEFAULT now(),
    updated_at      timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_reports_user_period UNIQUE (user_id, period_type, period_start),
    CONSTRAINT ck_reports_type CHECK (period_type IN ('weekly', 'monthly')),
    CONSTRAINT ck_reports_status CHECK (status IN ('generating', 'ready', 'failed', 'deleted')),
    CONSTRAINT ck_reports_mode CHECK (mode IN ('ai', 'rule'))
);
CREATE INDEX ix_reports_user_period ON reports (user_id, period_type, period_start DESC);

-- ---------- 9. 每日训练建议（侧栏常驻：事实快照 + 五段自然表达；一天一条，不设软删除） ----------
CREATE TABLE daily_advice (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    advice_date     date         NOT NULL,                  -- 建议所属日（一天一条）
    status          varchar(16)  NOT NULL DEFAULT 'generating',  -- generating / ready / failed
    mode            varchar(16)  NOT NULL DEFAULT 'ai',          -- ai / rule（无数据规则文案）
    verdict         varchar(64)  NULL,                     -- 自由结论：适合 / 适合但收敛 / 克制 / 休息 前缀 + 条件
    focus           varchar(120) NULL,                      -- 自由训练安排：动作方向、部位、避让
    intensity       varchar(64)  NULL,                      -- 自由强度：很低 / 低 / 中 / 高 / 很高 前缀 + RPE/时长
    body_parts      jsonb        NULL,                      -- 建议部位（最多 2 个）
    text            varchar(200) NULL,                      -- 侧栏五句正文（判断/训练/播报/提示/鼓励）
    facts           jsonb        NOT NULL,                  -- 事实快照（确定性计算，含硬约束）
    data_hash       varchar(64)  NOT NULL DEFAULT '',       -- facts 的 SHA-256（同日重算判断）
    model_name      varchar(64)  NULL,
    prompt_version  varchar(48)  NULL,
    generation_ms   integer      NOT NULL DEFAULT 0,
    attempts        integer      NOT NULL DEFAULT 0,        -- 当天尝试次数（失败重试上限）
    error_code      varchar(48)  NULL,
    error_message   varchar(500) NULL,
    generated_at    timestamp    NULL,
    created_at      timestamp    NOT NULL DEFAULT now(),
    updated_at      timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_daily_advice_user_date UNIQUE (user_id, advice_date),
    CONSTRAINT ck_daily_advice_status CHECK (status IN ('generating', 'ready', 'failed')),
    CONSTRAINT ck_daily_advice_mode CHECK (mode IN ('ai', 'rule'))
);

-- 定时任务（2026-11-17）：任务定义 + 执行记录
-- scheduled_jobs 是调度器的唯一事实源：应用启动时据此重建内存作业，不用 APScheduler 自带 job store
CREATE TABLE scheduled_jobs (
    id                    integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_key               varchar(64)  NOT NULL,               -- 对应 app/modules/system/scheduler/registry.py
    name                  varchar(64)  NOT NULL,               -- 显示名
    trigger_type          varchar(16)  NOT NULL,               -- cron / date / interval
    trigger_expr          varchar(128) NOT NULL,               -- 五段式 cron / 10m / 2026-11-20 15:40
    timezone              varchar(48)  NOT NULL DEFAULT 'Asia/Shanghai',
    params                jsonb        NOT NULL DEFAULT '{}'::jsonb,  -- 参数（结构由注册表 schema 约束）
    enabled               boolean      NOT NULL DEFAULT true,  -- 禁用则不注册内存作业
    misfire_grace_seconds integer      NULL,                   -- 空则用全局 scheduler_misfire_grace_seconds
    next_run_at           timestamp    NULL,                   -- 由调度器回写
    last_run_at           timestamp    NULL,
    last_status           varchar(16)  NULL,                   -- running / success / failed / skipped
    last_message          varchar(500) NULL,
    last_duration_ms      integer      NOT NULL DEFAULT 0,
    run_count             integer      NOT NULL DEFAULT 0,     -- 累计执行次数（含手动）
    created_at            timestamp    NOT NULL DEFAULT now(),
    updated_at            timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT ck_scheduled_jobs_trigger CHECK (trigger_type IN ('cron', 'date', 'interval'))
);
CREATE INDEX ix_scheduled_jobs_key ON scheduled_jobs (job_key);

CREATE TABLE job_runs (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id      integer      NULL REFERENCES scheduled_jobs (id) ON DELETE CASCADE,
    job_key     varchar(64)  NOT NULL,
    source      varchar(16)  NOT NULL,                         -- schedule / manual / cli
    status      varchar(16)  NOT NULL,                         -- running / success / failed / skipped
    started_at  timestamp    NOT NULL,
    finished_at timestamp    NULL,
    duration_ms integer      NOT NULL DEFAULT 0,
    message     varchar(500) NULL,
    detail      jsonb        NULL,                             -- 执行明细（如生成份数、失败条目）
    created_at  timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT ck_job_runs_status CHECK (status IN ('running', 'success', 'failed', 'skipped')),
    CONSTRAINT ck_job_runs_source CHECK (source IN ('schedule', 'manual', 'cli'))
);

-- ---------- 健康/运动档案（2026-11-26，按专项 skill 分套 + 一行一题） ----------
-- 同一套专项问题由 set_id 关联，一行一道题；skill_key 见 app/modules/profile/aspect_skills.py，
-- aspect 必须是该 skill 允许的固定方面；answer 为空表示已生成但尚未回答。
-- 同一用户同一套内 local_key(q1~q10) 唯一；同一专项最多保留最近 3 套（应用层约束）。
CREATE TABLE health_profile (
    id                integer   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    set_id            varchar(16) NOT NULL,
    skill_key         varchar(48) NOT NULL,
    aspect            varchar(32) NOT NULL,
    local_key         varchar(8)  NOT NULL,
    label             varchar(120) NOT NULL DEFAULT '',
    hint              varchar(120) NOT NULL DEFAULT '',
    placeholder       varchar(120) NOT NULL DEFAULT '',
    max_length        integer   NOT NULL DEFAULT 200,
    answer            text      NULL,
    sort_order        integer   NOT NULL DEFAULT 0,
    set_generated_at  timestamp NOT NULL,
    created_at        timestamp NOT NULL DEFAULT now(),
    updated_at        timestamp NOT NULL DEFAULT now(),
    CONSTRAINT uq_health_profile_user_set_local UNIQUE (user_id, set_id, local_key),
    CONSTRAINT ck_health_profile_aspect CHECK (
        aspect IN (
            'goal', 'diet', 'exercise', 'sport', 'training', 'sleep', 'lifestyle',
            'medical', 'cycle', 'psych', 'environment', 'preference',
            'posture', 'other'
        )
    ),
    CONSTRAINT ck_health_profile_max_length CHECK (max_length BETWEEN 50 AND 255)
);
CREATE INDEX idx_health_profile_user_skill
    ON health_profile (user_id, skill_key, set_generated_at);
CREATE INDEX ix_job_runs_job ON job_runs (job_id, started_at);

-- ---------- AI 模型配置（2026-11-27，三表：来源 / 模型 / 功能路由） ----------
-- 目标：把「每个 AI 功能用哪个模型」与「模型地址 + 凭据」从代码注册表与单一 .env 拆开，
-- 支持多来源（不同功能点可配不同地址与模型名）。三表为实例级配置，不挂 user_id，归管理员维护。
-- 三表由 app/ai/models/registry.py 运行时解析，/system/ai 管理页与 /api/system/ai-config 维护。
CREATE TABLE ai_providers (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_key    varchar(48)  NOT NULL,               -- 来源短标识（唯一）
    name            varchar(64)  NOT NULL,               -- 来源显示名
    base_url        varchar(255) NOT NULL,               -- OpenAI 兼容地址（不含密钥）
    api_key_env     varchar(64)  NOT NULL DEFAULT 'AI_API_KEY', -- 密钥所在环境变量
    api_key_cipher  text         NULL,                   -- 管理页写入的加密密钥；空则走 api_key_env
    timeout_seconds numeric(6,1) NOT NULL DEFAULT 30.0,  -- 来源默认读超时（秒）
    max_retries     integer      NOT NULL DEFAULT 1,     -- 默认重试次数
    extra_headers   jsonb        NOT NULL DEFAULT '{}'::jsonb,
    status          varchar(16)  NOT NULL DEFAULT 'active',
    remark          varchar(200) NOT NULL DEFAULT '',
    updated_by      integer      NULL,                   -- 最近维护人（逻辑外键）
    created_at      timestamp    NOT NULL DEFAULT now(),
    updated_at      timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_ai_providers_key UNIQUE (provider_key),
    CONSTRAINT ck_ai_providers_status CHECK (status IN ('active', 'disabled')),
    CONSTRAINT ck_ai_providers_timeout CHECK (timeout_seconds > 0),
    CONSTRAINT ck_ai_providers_retries CHECK (max_retries BETWEEN 0 AND 5)
);
CREATE INDEX ix_ai_providers_status ON ai_providers (status);

CREATE TABLE ai_models (
    id                         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias                      varchar(64)  NOT NULL,   -- 业务别名（代码/会话/前端只认它）
    provider_id                integer      NOT NULL REFERENCES ai_providers (id) ON DELETE RESTRICT,
    upstream_name              varchar(128) NOT NULL,   -- 真正发给服务商的 model 字段
    supports_text              boolean      NOT NULL DEFAULT true,
    supports_vision            boolean      NOT NULL DEFAULT false,
    supports_tools             boolean      NOT NULL DEFAULT false,
    supports_structured_output boolean      NOT NULL DEFAULT true,
    structured_method          varchar(24)  NOT NULL DEFAULT 'json_schema',
    timeout_seconds            numeric(6,1) NULL,       -- 空则用来源默认
    extra_body                 jsonb        NOT NULL DEFAULT '{}'::jsonb,
    params                     jsonb        NOT NULL DEFAULT '{}'::jsonb,
    selectable_for_chat        boolean      NOT NULL DEFAULT true,
    status                     varchar(16)  NOT NULL DEFAULT 'active',
    sort_order                 integer      NOT NULL DEFAULT 0,
    remark                     varchar(200) NOT NULL DEFAULT '',
    created_at                 timestamp    NOT NULL DEFAULT now(),
    updated_at                 timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_ai_models_alias UNIQUE (alias),
    CONSTRAINT ck_ai_models_status CHECK (status IN ('active', 'disabled')),
    CONSTRAINT ck_ai_models_method CHECK (structured_method IN ('json_schema', 'function_calling', 'json_mode')),
    CONSTRAINT ck_ai_models_timeout CHECK (timeout_seconds IS NULL OR timeout_seconds > 0)
);
CREATE INDEX ix_ai_models_provider ON ai_models (provider_id, status);

CREATE TABLE ai_feature_routes (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_key     varchar(64)  NOT NULL,               -- 功能键，取值由代码常量固定
    model_alias     varchar(64)  NOT NULL,               -- 目标模型别名（逻辑关联 ai_models.alias）
    timeout_seconds numeric(6,1) NULL,                   -- 空则依次用模型、来源默认
    params_override jsonb        NOT NULL DEFAULT '{}'::jsonb,
    enabled         boolean      NOT NULL DEFAULT true,  -- 停用回落 .env 与代码默认
    remark          varchar(200) NOT NULL DEFAULT '',
    created_at      timestamp    NOT NULL DEFAULT now(),
    updated_at      timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_ai_feature_routes_key UNIQUE (feature_key),
    CONSTRAINT ck_ai_feature_routes_timeout CHECK (timeout_seconds IS NULL OR timeout_seconds > 0)
);

